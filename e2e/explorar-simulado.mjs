/** E2E de Explorar y postular (mock). Mismos requisitos que flujo-completo.mjs, pero solo necesita web y backend para registrarse. Ejecutar desde web/ (guarda una captura en capturas/, que debe existir). */
import { chromium } from 'playwright-core';
import { rutaDeChrome } from './entorno.mjs';
const WEB = 'http://localhost:4200';
const b = await chromium.launch({ executablePath: rutaDeChrome });
const p = await (await b.newContext({ viewport: { width: 1280, height: 1000 } })).newPage();
const ok = (n) => console.log('  OK  ', n);
const correo = `exp-${Date.now().toString(36)}@cand.test`;
await p.goto(`${WEB}/registro`);
await p.locator('#nombre').fill('Eva Exploradora'); await p.locator('#correo').fill(correo);
await p.locator('#contrasena').fill('una-frase-larga-y-dificil');
await p.getByText('Autorizo el tratamiento').click();
await p.getByRole('button', { name: 'Crear cuenta' }).click();
await p.waitForURL('**/mis-pruebas');
await p.getByRole('link', { name: 'Explorar vacantes' }).click();
await p.getByRole('heading', { name: 'Explorar' }).waitFor(); ok('mis-pruebas vacío lleva a Explorar');
await p.getByText('Desarrollador backend Node.js').waitFor();
if (await p.locator('article').count() !== 5) throw new Error('catálogo');
ok('catálogo de 5 vacantes con aviso de demostración'); await p.getByText('Datos de demostración').waitFor();
await p.getByLabel('Buscar').fill('angular');
await p.waitForFunction(() => document.querySelectorAll('article').length === 1); ok('búsqueda por tecnología');
await p.getByLabel('Buscar').fill('');
await p.getByLabel('Modalidad').selectOption('remoto');
await p.waitForFunction(() => document.querySelectorAll('article').length === 2); ok('filtro por modalidad');
await p.getByLabel('Modalidad').selectOption('');
await p.locator('article', { hasText: 'Ingeniero de calidad' }).getByRole('button', { name: 'Postularme' }).click();
await p.getByText('Te postulaste a').waitFor();
await p.locator('article', { hasText: 'Ingeniero de calidad' }).getByText('En revisión').waitFor(); ok('postular y ver estado');
await p.reload();
await p.locator('article', { hasText: 'Ingeniero de calidad' }).getByText('En revisión').waitFor(); ok('la postulación persiste al recargar');
await p.getByRole('button', { name: /Mis postulaciones \(1\)/ }).click();
await p.waitForFunction(() => document.querySelectorAll('article').length === 1); ok('pestaña Mis postulaciones');
await p.screenshot({ path: 'e2e/explorar.png', fullPage: true });
await p.getByRole('button', { name: 'Retirar postulación' }).click();
await p.getByRole('alertdialog').getByRole('button', { name: 'Retirar' }).click();
await p.getByText('Aún no te has postulado').waitFor(); ok('retirar postulación con confirmación');
await b.close();
